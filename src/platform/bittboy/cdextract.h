// Miyoo Mini port: first-run extraction of the game files from the CD image.
//
// The GOG and Steam releases of Tomb Raider keep the DATA and FMV folders
// inside GAME.GOG, a raw image of the original CD (2352-byte sectors, the
// 2048 data bytes of each at offset 16). Getting them out needs CD-image
// tools most players do not have, so when a game folder holds such an image
// but lacks DATA or FMV, they are copied out here, once, with a progress
// screen. Each folder is first written as NAME.tmp and renamed at the end, so
// an interrupted run (battery, power button) leaves nothing half-copied
// behind: the next start redoes it. Plain 2048-byte .iso images work too.
//
// This runs before the game starts its video, so the screen is drawn straight
// into the framebuffer (/dev/fb0), upside down like the rest of the port: the
// Miyoo Mini Plus panel is mounted rotated by 180 degrees.

