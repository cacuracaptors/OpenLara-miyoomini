    struct Image {
        FILE *f;
        int   sectorSize;   // 2352 (raw) or 2048 (iso)
        int   dataOffset;   // where the 2048 data bytes start in a sector
    };

    struct Entry {
        char     name[64];
        uint32_t lba, size;
        bool     dir;
    };

    static char failReason[160] = "";

    static void fail(const char *what, const char *path) {
        snprintf(failReason, sizeof(failReason), "%s %s: %s", what, path, strerror(errno));
        fprintf(stderr, "extract: %s\n", failReason);
    }

    static uint32_t le32(const uint8_t *p) {
        return uint32_t(p[0]) | (uint32_t(p[1]) << 8) | (uint32_t(p[2]) << 16) | (uint32_t(p[3]) << 24);
    }

    // reads count sectors starting at lba; out receives count * 2048 bytes
    static bool readSectors(Image &img, uint32_t lba, int count, uint8_t *out) {
        static uint8_t raw[64 * 2352];
        if (count > 64) return false;
        if (fseeko(img.f, off_t(lba) * img.sectorSize, SEEK_SET) != 0) return false;
        size_t want = size_t(count) * img.sectorSize;
        if (fread(raw, 1, want, img.f) != want) return false;
        for (int i = 0; i < count; i++) {
            memcpy(out + i * 2048, raw + i * img.sectorSize + img.dataOffset, 2048);
        }
        return true;
    }

    static bool openImage(const char *path, Image &img) {
        img.f = fopen(path, "rb");
        if (!img.f) return false;
        static const int layouts[2][2] = { { 2352, 16 }, { 2048, 0 } };
        uint8_t pvd[2048];
        for (int i = 0; i < 2; i++) {
            img.sectorSize = layouts[i][0];
            img.dataOffset = layouts[i][1];
            if (readSectors(img, 16, 1, pvd) && pvd[0] == 1 && memcmp(pvd + 1, "CD001", 5) == 0) {
                return true;
            }
        }
        fclose(img.f);
        img.f = NULL;
        return false;
    }

    // Reads a directory's entries (without "." and "..") into list.
    static int listDir(Image &img, uint32_t lba, uint32_t size, Entry *list, int maxCount) {
        uint8_t buf[2048];
        int count = 0;
        for (uint32_t off = 0; off < size; off += 2048) {
            if (!readSectors(img, lba + off / 2048, 1, buf)) return -1;
            int p = 0;
            while (p + 34 <= 2048) {
                const uint8_t *r = buf + p;
                int len = r[0];
                if (len == 0) break;           // the rest of this sector is padding
                if (len < 34 || p + len > 2048) break;
                int nl = r[32];
                bool special = (nl == 1 && (r[33] == 0 || r[33] == 1));
                if (!special && 33 + nl <= len && count < maxCount) {
                    Entry &e = list[count++];
                    int n = nl < 63 ? nl : 63;
                    memcpy(e.name, r + 33, n);
                    e.name[n] = 0;
                    char *semi = strchr(e.name, ';');   // "FILE.EXT;1"
                    if (semi) *semi = 0;
                    int L = int(strlen(e.name));
                    if (L > 0 && e.name[L - 1] == '.') e.name[L - 1] = 0;
                    e.lba  = le32(r + 2);
                    e.size = le32(r + 10);
                    e.dir  = (r[25] & 2) != 0;
                }
                p += len;
            }
        }
        return count;
    }

    static Entry dirLists[4][1024];   // one list per nesting level (the CD is shallow)

    static bool sumDir(Image &img, const Entry &dir, int depth, uint64_t &total) {
        if (depth >= 4) return false;
        Entry *entries = dirLists[depth];
        int count = listDir(img, dir.lba, dir.size, entries, 1024);
        if (count < 0) return false;
        for (int i = 0; i < count; i++) {
            if (entries[i].dir) {
                Entry sub = entries[i];
                if (!sumDir(img, sub, depth + 1, total)) return false;
                count = listDir(img, dir.lba, dir.size, entries, 1024);   // reread: the level was reused
            } else {
                total += entries[i].size;
            }
        }
        return true;
    }

    static bool copyFile(Image &img, const Entry &e, const char *dst) {
        FILE *o = fopen(dst, "wb");
        if (!o) { fail("can't create", dst); return false; }
        static uint8_t buf[64 * 2048];
        uint32_t left = e.size, lba = e.lba;
        bool ok = true;
        while (left > 0 && ok) {
            uint32_t sectors = (left + 2047) / 2048;
            int n = sectors > 64 ? 64 : int(sectors);
            if (!readSectors(img, lba, n, buf)) {
                errno = EIO;
                fail("can't read (is the image complete?)", dst);
                ok = false;
                break;
            }
            uint32_t bytes = uint32_t(n) * 2048;
            if (bytes > left) bytes = left;
            if (fwrite(buf, 1, bytes, o) != bytes) { fail("can't write", dst); ok = false; }
            left      -= bytes;
            lba       += n;
            bytesDone += bytes;
            drawProgress();
        }
        if (fclose(o) != 0 && ok) { fail("can't finish", dst); ok = false; }
        return ok;
    }

    static bool extractDir(Image &img, const Entry &dir, const char *dst, int depth) {
        if (depth >= 4) return false;
        if (mkdir(dst, 0777) != 0) { fail("can't create folder", dst); return false; }
        Entry *entries = dirLists[depth];
        int count = listDir(img, dir.lba, dir.size, entries, 1024);
        if (count < 0) { errno = EIO; fail("can't read folder", dst); return false; }
        for (int i = 0; i < count; i++) {
            char path[512];
            snprintf(path, sizeof(path), "%s/%s", dst, entries[i].name);
            if (entries[i].dir) {
                Entry sub = entries[i];
                if (!extractDir(img, sub, path, depth + 1)) return false;
                count = listDir(img, dir.lba, dir.size, entries, 1024);   // reread: the level was reused
            } else {
                fprintf(stderr, "extract: %s (%u KB)\n", path, entries[i].size / 1024);
                if (!copyFile(img, entries[i], path)) return false;
            }
        }
        return true;
    }

    static void removeTree(const char *path) {
        DIR *d = opendir(path);
        if (d) {
            struct dirent *de;
            while ((de = readdir(d)) != NULL) {
                if (!strcmp(de->d_name, ".") || !strcmp(de->d_name, "..")) continue;
                char sub[512];
                snprintf(sub, sizeof(sub), "%s/%s", path, de->d_name);
                struct stat st;
                if (stat(sub, &st) == 0 && S_ISDIR(st.st_mode)) removeTree(sub); else unlink(sub);
            }
            closedir(d);
            rmdir(path);
        } else {
            unlink(path);
        }
    }

    // looks for a directory (isDir) or a file ending in suffix in the current
    // folder, ignoring case; copies the real name into out
    static bool findEntry(const char *name, bool isDir, const char *suffix, char *out, int outSize) {
        DIR *d = opendir(".");
        if (!d) return false;
        bool found = false;
        struct dirent *de;
        while (!found && (de = readdir(d)) != NULL) {
            struct stat st;
            if (stat(de->d_name, &st) != 0) continue;
            if (isDir != S_ISDIR(st.st_mode)) continue;
            if (name && strcasecmp(de->d_name, name) == 0) found = true;
            if (suffix) {
                int L = int(strlen(de->d_name)), S = int(strlen(suffix));
                if (L > S && strcasecmp(de->d_name + L - S, suffix) == 0) found = true;
            }
            if (found && out) snprintf(out, outSize, "%s", de->d_name);
        }
        closedir(d);
        return found;
    }

