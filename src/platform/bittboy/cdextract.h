    struct Screen {
        uint8_t *mem;       // first page
        int      w, h;      // visible size
        int      stride;    // bytes per line
        int      bpp;       // bytes per pixel: 2 or 4
        int      pages;     // pages in the virtual screen (double buffering)
        size_t   size;      // mapped bytes
    #ifdef CDX_TEST
        uint32_t *shadow;   // test build: logical (unrotated) copy for a PNG
    #endif
    };

    static Screen screen;   // zeroed: no framebuffer until screenOpen()
#ifdef CDX_TEST
    static void dumpScreen(const char *name);
#endif

    static void screenOpen() {
    #ifdef CDX_TEST
        screen.w = 640; screen.h = 480; screen.bpp = 4; screen.stride = 640 * 4; screen.pages = 1;
        screen.size = size_t(screen.stride) * screen.h;
        screen.mem = (uint8_t*)calloc(1, screen.size);
        screen.shadow = (uint32_t*)calloc(640 * 480, 4);
    #else
        int fd = open("/dev/fb0", O_RDWR);
        if (fd < 0) return;
        struct fb_var_screeninfo var;
        struct fb_fix_screeninfo fix;
        if (ioctl(fd, FBIOGET_VSCREENINFO, &var) == 0 && ioctl(fd, FBIOGET_FSCREENINFO, &fix) == 0 &&
            (var.bits_per_pixel == 16 || var.bits_per_pixel == 32)) {
            void *mem = mmap(NULL, fix.smem_len, PROT_READ | PROT_WRITE, MAP_SHARED, fd, 0);
            if (mem != MAP_FAILED) {
                screen.mem    = (uint8_t*)mem;
                screen.size   = fix.smem_len;
                screen.w      = int(var.xres);
                screen.h      = int(var.yres);
                screen.stride = int(fix.line_length);
                screen.bpp    = int(var.bits_per_pixel / 8);
                screen.pages  = var.yres ? int(var.yres_virtual / var.yres) : 1;
                if (screen.pages < 1) screen.pages = 1;
                if (size_t(screen.pages) * screen.h * screen.stride > screen.size) screen.pages = 1;
            }
        }
        close(fd);   // the mapping stays valid
    #endif
    }

    static void screenClose() {
    #ifndef CDX_TEST
        if (screen.mem) munmap(screen.mem, screen.size);
        screen.mem = NULL;
    #endif
    }

    // every page, so it shows whichever one the display is scanning out
    static void fillRect(int x0, int y0, int w, int h, uint32_t rgb) {
        if (!screen.mem) return;
        if (x0 < 0) { w += x0; x0 = 0; }
        if (y0 < 0) { h += y0; y0 = 0; }
        if (x0 + w > screen.w) w = screen.w - x0;
        if (y0 + h > screen.h) h = screen.h - y0;
        if (w <= 0 || h <= 0) return;
        const uint16_t c16 = uint16_t(((rgb >> 8) & 0xF800) | ((rgb >> 5) & 0x07E0) | ((rgb >> 3) & 0x001F));
        const uint32_t c32 = 0xFF000000u | rgb;
        for (int page = 0; page < screen.pages; page++) {
            uint8_t *base = screen.mem + size_t(page) * screen.h * screen.stride;
            for (int y = y0; y < y0 + h; y++) {
                // rotated by 180 degrees: logical (x, y) is physical (w-1-x, h-1-y)
                uint8_t *row = base + size_t(screen.h - 1 - y) * screen.stride;
                for (int x = x0; x < x0 + w; x++) {
                    const int px = screen.w - 1 - x;
                    if (screen.bpp == 4) ((uint32_t*)row)[px] = c32;
                    else                 ((uint16_t*)row)[px] = c16;
                }
            }
        }
    #ifdef CDX_TEST
        for (int y = y0; y < y0 + h; y++)
            for (int x = x0; x < x0 + w; x++) screen.shadow[y * 640 + x] = rgb;
    #endif
    }

    static int textWidth(const char *s, int scale) {
        return int(strlen(s)) * FONT_W * scale;
    }

    static void drawText(int x, int y, const char *s, int scale, uint32_t rgb) {
        for (; *s; s++, x += FONT_W * scale) {
            int ch = (unsigned char)*s;
            if (ch < 32 || ch > 126) ch = '?';
            const uint16_t *glyph = font + (ch - 32) * FONT_H;
            for (int gy = 0; gy < FONT_H; gy++) {
                const uint16_t bits = glyph[gy];
                if (!bits) continue;
                for (int gx = 0; gx < FONT_W; gx++) {
                    if (bits & (1 << (FONT_W - 1 - gx))) {
                        fillRect(x + gx * scale, y + gy * scale, scale, scale, rgb);
                    }
                }
            }
        }
    }

    static void drawCentered(int y, const char *s, int scale, uint32_t rgb) {
        drawText((screen.w - textWidth(s, scale)) / 2, y, s, scale, rgb);
    }

