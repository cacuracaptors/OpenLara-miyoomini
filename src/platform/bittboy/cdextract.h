    static void finish(Image &img, int waitSeconds, bool quit) {
        if (img.f) fclose(img.f);
        img.f = NULL;
    #ifdef CDX_TEST
        (void)waitSeconds;
        dumpScreen("final.ppm");
    #else
        sleep(waitSeconds);
    #endif
        screenClose();
        if (quit) exit(0);   // back to the OnionOS menu; the game can't run without its files
    }

    static void extractGameFiles() {
        static const char *wanted[] = { "DATA", "FMV" };
        bool need[2];
        bool any = false;
        for (int i = 0; i < 2; i++) {
            need[i] = !findEntry(wanted[i], true, NULL, NULL, 0);
            any |= need[i];
        }
        if (!any) return;

        char imagePath[256];
        if (!findEntry(NULL, false, ".gog", imagePath, sizeof(imagePath)) &&
            !findEntry(NULL, false, ".iso", imagePath, sizeof(imagePath))) {
            return;
        }

        Image img;
        if (!openImage(imagePath, img)) {
            fprintf(stderr, "extract: %s is not a readable CD image\n", imagePath);
            return;
        }

        uint8_t pvd[2048];
        Entry rootList[256];
        int count = -1;
        if (readSectors(img, 16, 1, pvd)) {
            const uint8_t *root = pvd + 156;
            count = listDir(img, le32(root + 2), le32(root + 10), rootList, 256);
        }

        int found[2] = { -1, -1 };
        bytesTotal = 0;
        for (int i = 0; i < 2 && count > 0; i++) {
            if (!need[i]) continue;
            for (int k = 0; k < count; k++) {
                if (rootList[k].dir && strcasecmp(rootList[k].name, wanted[i]) == 0) {
                    found[i] = k;
                    sumDir(img, rootList[k], 0, bytesTotal);
                    break;
                }
            }
        }
        if (found[0] < 0 && found[1] < 0) { fclose(img.f); return; }

        struct stat imageStat;
        const int imageMB = stat(imagePath, &imageStat) == 0 ? int(imageStat.st_size / (1024 * 1024)) : 0;

        screenOpen();
        char line[320];
        snprintf(line, sizeof(line), "Copying the game files out of %s.", imagePath);
        drawScreen(line, "This takes about a minute and only happens once.", COLOR_TEXT);

        // enough room? (plus a margin for saves and logs)
        const uint64_t needBytes = bytesTotal + 8ull * 1024 * 1024;
        struct statvfs vfs;
        if (statvfs(".", &vfs) == 0) {
            const uint64_t freeBytes = uint64_t(vfs.f_bavail) * vfs.f_frsize;
            if (freeBytes < needBytes) {
                fprintf(stderr, "extract: not enough space: %llu MB needed, %llu MB free\n",
                        (unsigned long long)(needBytes >> 20), (unsigned long long)(freeBytes >> 20));
                char l1[96], l2[96];
                snprintf(l1, sizeof(l1), "Not enough free space on the SD card:");
                snprintf(l2, sizeof(l2), "%llu MB needed, %llu MB free.",
                         (unsigned long long)(needBytes >> 20), (unsigned long long)(freeBytes >> 20));
                drawScreen(l1, l2, COLOR_ERROR);
                drawStatus("Free some space and start the game again.", "", COLOR_TEXT);
                finish(img, 8, true);
                return;
            }
        }

        bytesDone = 0;
        shownPercent = -1;
        drawProgress();

        bool ok = true;
        for (int i = 0; i < 2 && ok; i++) {
            if (found[i] < 0) continue;
            char tmp[64];
            snprintf(tmp, sizeof(tmp), "%s.tmp", wanted[i]);
            removeTree(tmp);   // left over by an interrupted run
            fprintf(stderr, "extract: copying %s out of %s (first run only)\n", wanted[i], imagePath);
            ok = extractDir(img, rootList[found[i]], tmp, 0);
            if (ok && rename(tmp, wanted[i]) != 0) {
                fail("can't rename", tmp);
                ok = false;
            }
            if (ok) {
                fprintf(stderr, "extract: %s done\n", wanted[i]);
            } else {
                fprintf(stderr, "extract: %s FAILED\n", wanted[i]);
                removeTree(tmp);
            }
        }

        if (ok) {
            // Everything the game needs is out, so the image is no longer used:
            // remove it (only when both folders are really there).
            fclose(img.f);
            img.f = NULL;
            char l1[320], l2[96];
            if (findEntry("DATA", true, NULL, NULL, 0) && findEntry("FMV", true, NULL, NULL, 0) && unlink(imagePath) == 0) {
                fprintf(stderr, "extract: %s removed, %d MB freed\n", imagePath, imageMB);
                snprintf(l1, sizeof(l1), "Done! %s was removed", imagePath);
            } else {
                snprintf(l1, sizeof(l1), "Done! You can now delete %s", imagePath);
            }
            snprintf(l2, sizeof(l2), "to free %d MB. Starting the game...", imageMB);
            drawStatus(l1, l2, COLOR_TEXT);
            finish(img, 4, false);
        } else {
            drawStatus("Copying failed. The reason is in log.txt,", "in this game's folder.", COLOR_ERROR);
            finish(img, 8, true);
        }
    }
